import Foundation

enum YouTubeMetadata {
    static func text(_ json: JSON) -> String? {
        if let value = json.string, json.raw is String { return value }
        if let value = json["simpleText"].string { return value }
        let value = json["runs"].array.compactMap { $0["text"].string }.joined()
        return value.isEmpty ? nil : value
    }
    static func walk(_ json: JSON, depth: Int = 0, visit: (String, JSON) -> Void) {
        guard depth < 80 else { return }
        if let dict = json.dict {
            for (key, value) in dict { visit(key, value); walk(value, depth: depth + 1, visit: visit) }
        } else {
            for value in json.array { walk(value, depth: depth + 1, visit: visit) }
        }
    }
    static func withPoToken(_ tracks: [SubtitleTrack], token: String?, client: String) -> [SubtitleTrack] {
        guard let token, !token.isEmpty else { return tracks }
        return tracks.map { track in
            guard var url = URLComponents(url: track.url, resolvingAgainstBaseURL: false) else { return track }
            url.queryItems = (url.queryItems ?? []).filter { !["pot", "potc", "c"].contains($0.name) }
                + [URLQueryItem(name: "pot", value: token), URLQueryItem(name: "potc", value: "1"), URLQueryItem(name: "c", value: client)]
            var result = track; result.url = url.url ?? track.url
            return result
        }
    }
    static func subtitles(from response: JSON) -> [SubtitleTrack] {
        let captions = response["captions"]["playerCaptionsTracklistRenderer"]
        var tracks: [SubtitleTrack] = []
        for track in captions["captionTracks"].array {
            guard let base = track["baseUrl"].string, var components = URLComponents(string: base) else { continue }
            let language = track["languageCode"].string ?? "und"
            components.queryItems = (components.queryItems ?? []).filter { $0.name != "fmt" } + [URLQueryItem(name: "fmt", value: "json3")]
            guard let url = components.url else { continue }
            tracks.append(SubtitleTrack(language: language, name: text(track["name"]), isAutoGenerated: track["kind"].string == "asr", url: url, formatHint: "youtube-json3"))
            if track["isTranslatable"].bool == true {
                for target in captions["translationLanguages"].array {
                    guard let targetLanguage = target["languageCode"].string, targetLanguage != language else { continue }
                    var translated = components
                    translated.queryItems = (translated.queryItems ?? []).filter { $0.name != "tlang" } + [URLQueryItem(name: "tlang", value: targetLanguage)]
                    if let translatedURL = translated.url {
                        tracks.append(SubtitleTrack(language: targetLanguage, name: text(target["languageName"]), isAutoGenerated: true,
                            url: translatedURL, formatHint: "youtube-json3", sourceLanguage: language, isTranslated: true))
                    }
                }
            }
        }
        var seen = Set<String>()
        return tracks.filter { seen.insert($0.url.absoluteString).inserted }
    }
    static func enrich(_ info: inout MediaInfo, from data: JSON) {
        var chapters: [MediaChapter] = []
        walk(data) { key, value in
            switch key {
            case "chapterRenderer":
                if let milliseconds = value["timeRangeStartMillis"].double,
                   let title = text(value["title"]) { chapters.append(MediaChapter(title: title, start: milliseconds / 1000)) }
            case "macroMarkersListItemRenderer":
                if let seconds = value["onTap"]["watchEndpoint"]["startTimeSeconds"].double, let title = text(value["title"]) {
                    chapters.append(MediaChapter(title: title, start: seconds))
                }
            case "videoPrimaryInfoRenderer":
                if let title = text(value["title"]), info.title == "(untitled)" { info.title = title }
                if let likes = value["videoActions"]["menuRenderer"]["topLevelButtons"].array.first?["segmentedLikeDislikeButtonViewModel"]["likeButtonViewModel"]["likeButtonViewModel"]["toggleButtonViewModel"]["toggleButtonViewModel"]["defaultButtonViewModel"]["buttonViewModel"]["title"].string {
                    info.extras["likeCountText"] = likes
                }
            case "videoSecondaryInfoRenderer":
                if let description = text(value["description"]), info.videoDescription?.isEmpty != false { info.videoDescription = description }
                if let category = value["metadataRowContainer"]["metadataRowContainerRenderer"]["rows"].array.first?["metadataRowRenderer"]["contents"][0]["runs"][0]["text"].string {
                    info.extras["category"] = category
                }
            case "videoOwnerRenderer":
                if let count = text(value["subscriberCountText"]) { info.extras["channelFollowerCountText"] = count }
            case "liveChatRenderer": info.extras["liveChatAvailable"] = "true"
            default: break
            }
        }
        if !chapters.isEmpty {
            var seen = Set<Double>()
            chapters = chapters.sorted { $0.start < $1.start }.filter { seen.insert($0.start).inserted }
            for index in chapters.indices { chapters[index].end = index + 1 < chapters.count ? chapters[index + 1].start : info.duration }
            info.chapters = chapters
        }
    }
}

public struct YouTubeComment: Codable, Sendable, Equatable {
    public var id: String
    public var author: String?
    public var authorChannelID: String?
    public var text: String
    public var publishedText: String?
    public var likesText: String?
    public var parentID: String?
}
public struct YouTubeCommentPage: Sendable {
    public var comments: [YouTubeComment]
    public var continuation: String?
}
public struct YouTubeChatMessage: Codable, Sendable, Equatable {
    public var id: String
    public var author: String?
    public var text: String
    public var timestampMicroseconds: String?
    public var type: String
    public var amount: String?
}
public struct YouTubeChatPage: Sendable {
    public var messages: [YouTubeChatMessage]
    public var removedMessageIDs: [String]
    public var continuation: String?
    public var pollAfterMilliseconds: Int?
}

/// Read-only comments/live-chat pagination. No posting, account mutation or external backend.
public struct YouTubeDiscussionService: Sendable {
    public init() {}
    public func comments(videoID: String, continuation: String? = nil, options: ExtractionOptions = ExtractionOptions()) async throws -> YouTubeCommentPage {
        let context = ExtractionContext.make(options: options)
        let client = InnerTubeClient(http: context.http, cookies: context.cookies)
        if let continuation { return Self.parseComments(try await client.next(continuation: continuation)) }
        let response = try await client.next(videoID: videoID)
        var token: String?
        YouTubeMetadata.walk(response) { key, value in
            if key == "itemSectionRenderer", value["sectionIdentifier"].string == "comment-item-section" {
                token = Self.continuation(value)
            }
        }
        guard let token else { return Self.parseComments(response) }
        return Self.parseComments(try await client.next(continuation: token))
    }
    public func chat(videoID: String, continuation: String? = nil, replay: Bool = false,
                     options: ExtractionOptions = ExtractionOptions()) async throws -> YouTubeChatPage {
        let context = ExtractionContext.make(options: options)
        let client = InnerTubeClient(http: context.http, cookies: context.cookies)
        var token = continuation
        if token == nil {
            let session = YouTubeSession.parse(try await client.watchPage(videoID: videoID), videoID: videoID)
            if let data = session.initialData {
                YouTubeMetadata.walk(data) { key, value in if key == "liveChatRenderer" { token = Self.continuation(value) } }
            }
        }
        guard let token else { throw ExtractionError.notExtractable(site: "youtube", reason: "此视频没有可读取的直播聊天") }
        return Self.parseChat(try await client.liveChat(continuation: token, replay: replay))
    }
    public func chatStream(videoID: String, replay: Bool = false, options: ExtractionOptions = ExtractionOptions()) -> AsyncThrowingStream<YouTubeChatMessage, Error> {
        AsyncThrowingStream { continuation in
            let task = Task {
                do {
                    var token: String?, seen = Set<String>()
                    repeat {
                        try Task.checkCancellation()
                        let page = try await chat(videoID: videoID, continuation: token, replay: replay, options: options)
                        for message in page.messages where seen.insert(message.id).inserted { continuation.yield(message) }
                        token = page.continuation
                        if token != nil { try await Task.sleep(for: .milliseconds(max(100, page.pollAfterMilliseconds ?? 1000))) }
                    } while token != nil
                    continuation.finish()
                } catch { continuation.finish(throwing: error) }
            }
            continuation.onTermination = { _ in task.cancel() }
        }
    }

    static func continuation(_ json: JSON) -> String? {
        var token: String?
        YouTubeMetadata.walk(json) { key, value in
            if ["continuationCommand","reloadContinuationData","timedContinuationData","invalidationContinuationData","liveChatReplayContinuationData"].contains(key), token == nil {
                token = value["token"].string ?? value["continuation"].string
            }
        }
        return token
    }
    static func parseComments(_ json: JSON) -> YouTubeCommentPage {
        var comments: [YouTubeComment] = []
        YouTubeMetadata.walk(json) { key, value in
            if key == "commentRenderer", let id = value["commentId"].string {
                comments.append(YouTubeComment(id: id, author: YouTubeMetadata.text(value["authorText"]),
                    authorChannelID: value["authorEndpoint"]["browseEndpoint"]["browseId"].string,
                    text: YouTubeMetadata.text(value["contentText"]) ?? "", publishedText: YouTubeMetadata.text(value["publishedTimeText"]),
                    likesText: value["voteCount"].string ?? YouTubeMetadata.text(value["voteCount"]), parentID: value["parentCommentId"].string))
            } else if key == "commentEntityPayload", let id = value["properties"]["commentId"].string {
                comments.append(YouTubeComment(id: id, author: value["author"]["displayName"].string,
                    authorChannelID: value["author"]["channelId"].string, text: value["properties"]["content"]["content"].string ?? "",
                    publishedText: value["properties"]["publishedTime"].string, likesText: value["toolbar"]["likeCountNotliked"].string,
                    parentID: value["properties"]["parentCommentId"].string))
            }
        }
        var seen = Set<String>()
        return YouTubeCommentPage(comments: comments.filter { seen.insert($0.id).inserted }, continuation: continuation(json))
    }
    static func parseChat(_ json: JSON) -> YouTubeChatPage {
        var messages: [YouTubeChatMessage] = [], removed: [String] = [], wait: Int?
        YouTubeMetadata.walk(json) { key, value in
            if key.hasPrefix("liveChat"), key.hasSuffix("Renderer"), let id = value["id"].string {
                messages.append(YouTubeChatMessage(id: id, author: YouTubeMetadata.text(value["authorName"]),
                    text: YouTubeMetadata.text(value["message"]) ?? YouTubeMetadata.text(value["headerSubtext"]) ?? "",
                    timestampMicroseconds: value["timestampUsec"].string, type: key, amount: YouTubeMetadata.text(value["purchaseAmountText"])))
            }
            if key == "removeChatItemAction", let id = value["targetItemId"].string { removed.append(id) }
            if key == "timedContinuationData" { wait = value["timeoutMs"].int }
        }
        var seen = Set<String>()
        return YouTubeChatPage(messages: messages.filter { seen.insert($0.id).inserted }, removedMessageIDs: removed,
                               continuation: continuation(json), pollAfterMilliseconds: wait)
    }
}
