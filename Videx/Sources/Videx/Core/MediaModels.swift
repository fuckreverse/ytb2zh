import Foundation

// MARK: - Media Kind

/// 流的类型：混合流（音视频合一）、纯视频流、纯音频流。
public enum MediaKind: String, Codable, Sendable {
    case muxed
    case videoOnly
    case audioOnly
}

/// 流的传输协议。
public enum MediaProtocol: String, Codable, Sendable {
    case https
    case hls
    case dash
}

// MARK: - Media Format

/// 一条可下载的媒体流。
public struct MediaFormat: Codable, Sendable, Equatable {
    /// 站点内部的格式 ID（YouTube itag / B 站 quality id 等）。
    public var formatID: String
    public var kind: MediaKind
    public var url: URL
    /// 容器/扩展名（mp4、webm、m4a…）。
    public var container: String?
    public var videoCodec: String?
    public var audioCodec: String?
    public var width: Int?
    public var height: Int?
    public var fps: Int?
    public var averageBitrate: Int?
    /// 若站点返回了确切大小（字节），否则为 nil（可自行 HEAD 探测）。
    public var approximateSize: Int64?
    public var protocolType: MediaProtocol
    /// 音频轨语言（多语言配音场景）。
    public var language: String?
    /// 人类可读的画质标签，如 "1080p"、"720p60"、"DASH 高清 1080P"。
    public var qualityLabel: String?
    /// 备用 URL（B 站 multi-CDN 场景）。
    public var backupURLs: [URL]?

    public init(
        formatID: String,
        kind: MediaKind,
        url: URL,
        container: String? = nil,
        videoCodec: String? = nil,
        audioCodec: String? = nil,
        width: Int? = nil,
        height: Int? = nil,
        fps: Int? = nil,
        averageBitrate: Int? = nil,
        approximateSize: Int64? = nil,
        protocolType: MediaProtocol = .https,
        language: String? = nil,
        qualityLabel: String? = nil,
        backupURLs: [URL]? = nil
    ) {
        self.formatID = formatID
        self.kind = kind
        self.url = url
        self.container = container
        self.videoCodec = videoCodec
        self.audioCodec = audioCodec
        self.width = width
        self.height = height
        self.fps = fps
        self.averageBitrate = averageBitrate
        self.approximateSize = approximateSize
        self.protocolType = protocolType
        self.language = language
        self.qualityLabel = qualityLabel
        self.backupURLs = backupURLs
    }
}

// MARK: - Subtitle Track

/// 一条字幕轨（URL 惰性取用，不默认下载）。
public struct SubtitleTrack: Codable, Sendable, Equatable {
    public var language: String
    public var name: String?
    public var isAutoGenerated: Bool
    public var url: URL
    /// 原始格式标识（youtube-json3 / bilibili-json / srv3 …）。
    public var formatHint: String

    public init(
        language: String,
        name: String? = nil,
        isAutoGenerated: Bool = false,
        url: URL,
        formatHint: String
    ) {
        self.language = language
        self.name = name
        self.isAutoGenerated = isAutoGenerated
        self.url = url
        self.formatHint = formatHint
    }
}

// MARK: - Media Info

/// 一次成功提取的完整结果。
public struct MediaInfo: Codable, Sendable, Equatable {
    /// 提取器 ID（"youtube" / "bilibili"）。
    public var extractorID: String
    public var id: String
    public var title: String
    public var webpageURL: URL
    public var uploader: String?
    public var channelID: String?
    public var duration: TimeInterval?
    public var viewCount: Int64?
    public var uploadDate: String?   // yyyyMMdd
    public var videoDescription: String?
    public var thumbnailURL: URL?
    /// 排序约定：muxed 在前，视频流按清晰度降序，音频流在后。
    public var formats: [MediaFormat]
    public var subtitles: [SubtitleTrack]
    /// 站点特有附加信息（自由键值）。
    public var extras: [String: String]

    public init(
        extractorID: String,
        id: String,
        title: String,
        webpageURL: URL,
        uploader: String? = nil,
        channelID: String? = nil,
        duration: TimeInterval? = nil,
        viewCount: Int64? = nil,
        uploadDate: String? = nil,
        videoDescription: String? = nil,
        thumbnailURL: URL? = nil,
        formats: [MediaFormat] = [],
        subtitles: [SubtitleTrack] = [],
        extras: [String: String] = [:]
    ) {
        self.extractorID = extractorID
        self.id = id
        self.title = title
        self.webpageURL = webpageURL
        self.uploader = uploader
        self.channelID = channelID
        self.duration = duration
        self.viewCount = viewCount
        self.uploadDate = uploadDate
        self.videoDescription = videoDescription
        self.thumbnailURL = thumbnailURL
        self.formats = formats
        self.subtitles = subtitles
        self.extras = extras
    }

    /// 最高清的纯视频流。
    public var bestVideoOnly: MediaFormat? {
        formats.filter { $0.kind == .videoOnly }
            .sorted { ($0.height ?? 0, $0.averageBitrate ?? 0) > ($1.height ?? 0, $1.averageBitrate ?? 0) }
            .first
    }

    /// 最高码率的纯音频流。
    public var bestAudioOnly: MediaFormat? {
        formats.filter { $0.kind == .audioOnly }
            .sorted { ($0.averageBitrate ?? 0) > ($1.averageBitrate ?? 0) }
            .first
    }

    /// 最高清的混合流（音视频合一，可直接播放）。
    public var bestMuxed: MediaFormat? {
        formats.filter { $0.kind == .muxed }
            .sorted { ($0.height ?? 0, $0.averageBitrate ?? 0) > ($1.height ?? 0, $1.averageBitrate ?? 0) }
            .first
    }
}

// MARK: - Sort

extension [MediaFormat] {
    /// 按 muxed > 视频清晰度 > 音频码率 排序整理。
    public func sortedForDisplay() -> [MediaFormat] {
        sorted { a, b in
            let rankA = a.kind == .muxed ? 0 : (a.kind == .videoOnly ? 1 : 2)
            let rankB = b.kind == .muxed ? 0 : (b.kind == .videoOnly ? 1 : 2)
            if rankA != rankB { return rankA < rankB }
            switch a.kind {
            case .audioOnly:
                return (a.averageBitrate ?? 0) > (b.averageBitrate ?? 0)
            default:
                return (a.height ?? 0, a.averageBitrate ?? 0) > (b.height ?? 0, b.averageBitrate ?? 0)
            }
        }
    }
}
