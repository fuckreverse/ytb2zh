extension YouTubeExtractor {
    func playabilityReasonPublic(_ response: JSON) -> ExtractionError? {
        playabilityReason(response)
    }

    func buildMediaInfoPublic(videoID: String, response: JSON, formats: [MediaFormat]) -> MediaInfo {
        buildMediaInfo(videoID: videoID, response: response, formats: formats)
    }
}

extension StreamURLSolver {
    /// 便捷方法：同时解析 formats + adaptiveFormats（批量两阶段）。
    func formats(from response: JSON, challenge: PlayerChallenge?) async throws -> [MediaFormat] {
        var raw: [(json: JSON, kind: MediaKind)] = []
        for f in response["streamingData"]["formats"].array { raw.append((f, .muxed)) }
        for f in response["streamingData"]["adaptiveFormats"].array {
            let mime = f["mimeType"].string ?? ""
            let kind: MediaKind = mime.hasPrefix("audio/") ? .audioOnly : .videoOnly
            raw.append((f, kind))
        }

        var sigMap: [String: String] = [:]
        if let challenge {
            let sigs = raw.compactMap { item -> String? in
                guard let cipher = item.json["signatureCipher"].string else { return nil }
                return QueryString.parse(cipher)["s"]
            }
            if !sigs.isEmpty { sigMap = challenge.decipherBatch(sigs, js: context.js) }
        }

        var resolved: [(json: JSON, kind: MediaKind, urlString: String)] = []
        var nInputs: [String] = []
        for (json, kind) in raw {
            if let urlString = baseURL(from: json, sigMap: sigMap) {
                resolved.append((json, kind, urlString))
                if let n = nParam(of: urlString) { nInputs.append(n) }
            }
        }

        var nMap: [String: String] = [:]
        if let challenge, !nInputs.isEmpty {
            nMap = challenge.solveNsigBatch(nInputs, js: context.js)
        }

        var result: [MediaFormat] = []
        for item in resolved {
            if let m = mediaFormat(from: item.json, kind: item.kind, urlString: item.urlString, nMap: nMap) {
                result.append(m)
            }
        }
        return result
    }
}

